#!/usr/bin/env python3
"""Compile checked-in schemas into Python bindings compatible with protobuf 4.25+.

The compiler supplies descriptors, including maps and imports. A small standard
builder wrapper keeps the SDK usable on Python 3.8 without requiring a runtime
as new as the developer's protoc. The private pool also lets older, independently
published joystickmagic bindings coexist with the new controller schema.
"""
import argparse
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from google.protobuf import descriptor_pb2

ROOT = Path(__file__).resolve().parents[1]
PROTO = ROOT / "asmagic" / "proto"
SCHEMAS = PROTO / "schemas"


def compile_descriptors():
    compiler = shutil.which("protoc")
    command = [compiler] if compiler else [sys.executable, "-m", "grpc_tools.protoc"]
    with tempfile.TemporaryDirectory() as directory:
        output = Path(directory) / "schema.pb"
        subprocess.run(command + ["--proto_path=" + str(SCHEMAS),
                                  "--include_imports", "--descriptor_set_out=" + str(output)]
                       + [p.name for p in sorted(SCHEMAS.glob("*.proto"))], check=True)
        files = descriptor_pb2.FileDescriptorSet.FromString(output.read_bytes()).file
        return list(files)


def render(file):
    module = file.name.replace(".proto", "_pb2")
    imports = "".join("from . import " + name.replace(".proto", "_pb2") + "\n"
                      for name in file.dependency)
    return ("# Generated by tools/generate_protos.py from " + file.name + ". DO NOT EDIT.\n"
            "from google.protobuf.internal import builder as _builder\n"
            "from ._pool import POOL as _pool\n" + imports + "\n"
            "DESCRIPTOR = _pool.AddSerializedFile(" + repr(file.SerializeToString()) + ")\n"
            "_builder.BuildMessageAndEnumDescriptors(DESCRIPTOR, globals())\n"
            "_builder.BuildTopDescriptorsAndMessages(DESCRIPTOR, 'asmagic.proto."
            + module + "', globals())\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated bindings are stale")
    args = parser.parse_args()
    stale = []
    for descriptor in compile_descriptors():
        target = PROTO / descriptor.name.replace(".proto", "_pb2.py")
        content = render(descriptor)
        if args.check:
            if not target.exists() or target.read_text() != content:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.write_text(content)
    if stale:
        parser.exit(1, "Stale bindings: " + ", ".join(stale) + "\n")
    print("Protobuf bindings " + ("verified" if args.check else "generated"))


if __name__ == "__main__":
    main()
